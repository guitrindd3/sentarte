/** Decoded bitmaps: rows of "X"/"." like the hand-drawn figures. */
export const ICONES: Record<string, string[]> = Object.fromEntries(
  Object.entries(CODIGOS).map(([k, v]) => {
    const [w, hex] = v.split(":");
    const largura = Number(w);
    const linhas: string[] = [];
    for (let p = 0; p < hex.length; p += 5) {
      const bits = parseInt(hex.slice(p, p + 5), 16).toString(2).padStart(largura, "0");
      linhas.push(bits.replace(/1/g, "X").replace(/0/g, "."));
    }
    return [k, linhas];
  })
);

