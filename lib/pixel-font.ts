export const GLYPH_W = 5;
export const GLYPH_H = 7;

/** Uppercase, strip accents, drop anything the font can't draw. */
export function normalizarTexto(texto: string) {
  return texto
    .toUpperCase()
    .normalize("NFD")
    .replace(/\p{Diacritic}/gu, "")
    .split("")
    .filter((c) => c in GLYPHS)
    .join("");
}

/** Whether pixel (col,row) of character `c` is set. */
export function glyphPixel(c: string, col: number, row: number) {
  const g = GLYPHS[c];
  if (!g || col < 0 || col >= GLYPH_W || row < 0 || row >= GLYPH_H) return false;
  return ((g[row] >> (GLYPH_W - 1 - col)) & 1) === 1;
}
